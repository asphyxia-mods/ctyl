// Package render produces the per-line apko configuration from the shared
// base definition and the policy, so Java lines never diverge in layout.
package render

import (
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"

	"go.yaml.in/yaml/v3"

	"ctyl/internal/policy"
)

const BaseConfig = "images/runtime-base.apko.yaml"

type Input struct {
	Policy       *policy.Policy
	Line         policy.Line
	Distribution string
	// VendorPackage names the locally built package for vendor distributions.
	VendorPackage string
	// Constraints pin package versions ("name=version"), for emergency
	// rollbacks of a broken upstream package and for regression tests.
	Constraints []string
	Now         time.Time
}

type pathEntry struct {
	Path        string `yaml:"path"`
	Type        string `yaml:"type"`
	Permissions uint32 `yaml:"permissions"`
	UID         *int   `yaml:"uid,omitempty"`
	GID         *int   `yaml:"gid,omitempty"`
}

type config struct {
	Include  string `yaml:"include"`
	Contents struct {
		Packages []string `yaml:"packages"`
	} `yaml:"contents"`
	Paths       []pathEntry       `yaml:"paths,omitempty"`
	Environment map[string]string `yaml:"environment"`
}

// Render returns the apko YAML for a line and distribution.
func Render(in Input) ([]byte, error) {
	dist, ok := in.Policy.Distributions[in.Distribution]
	if !ok {
		return nil, fmt.Errorf("unknown distribution %q", in.Distribution)
	}
	var c config
	c.Include = BaseConfig
	switch dist.Kind {
	case "wolfi":
		for _, p := range dist.Packages {
			c.Contents.Packages = append(c.Contents.Packages, policy.Expand(p, in.Line))
		}
		c.Contents.Packages = append(c.Contents.Packages, in.Line.ExtraPackages...)
		for _, pin := range in.Constraints {
			name, _, ok := strings.Cut(pin, "=")
			if !ok || !safeRE.MatchString(strings.ReplaceAll(pin, "=", "")) {
				return nil, fmt.Errorf("invalid package constraint %q (want name=version)", pin)
			}
			replaced := false
			for i, p := range c.Contents.Packages {
				if p == name {
					c.Contents.Packages[i], replaced = pin, true
				}
			}
			if !replaced {
				c.Contents.Packages = append(c.Contents.Packages, pin)
			}
		}
		for _, exe := range in.Line.DisableExecutables {
			c.Paths = append(c.Paths, pathEntry{Path: exe, Type: "permissions", Permissions: 0})
		}
	default:
		if in.VendorPackage == "" {
			return nil, fmt.Errorf("distribution %s needs a locally built vendor package", in.Distribution)
		}
		c.Contents.Packages = []string{in.VendorPackage + "@ctyl"}
	}
	zero := 0
	c.Paths = append(c.Paths, pathEntry{Path: "/var/tmp", Type: "directory", Permissions: 0o1777, UID: &zero, GID: &zero})

	c.Environment = map[string]string{
		"CTYL_IMAGE":             fmt.Sprintf("%s (%s)", in.Line.Tag, in.Distribution),
		"CTYL_JAVA_MAJOR":        fmt.Sprint(in.Line.Major),
		"CTYL_JAVA_DISTRIBUTION": in.Distribution,
	}
	if opts := in.Policy.ActiveMitigations(in.Line.Major, in.Now); len(opts) > 0 {
		sort.Strings(opts)
		c.Environment["JDK_JAVA_OPTIONS"] = strings.Join(opts, " ")
	}

	out, err := yaml.Marshal(&c)
	if err != nil {
		return nil, err
	}
	header := fmt.Sprintf("# Generated by `ctyl render --line %d --distribution %s`. Do not edit.\n", in.Line.Major, in.Distribution)
	return append([]byte(header), out...), nil
}

// VendorArchive is the subset of a verified vendor download the recipe needs.
type VendorArchive struct {
	Arch, File, SHA256, TopDir string
}

type VendorInput struct {
	Line         policy.Line
	Distribution string
	Version      string
	License      string
	Archives     []VendorArchive
}

// VendorPackageName is the apk name of a repackaged vendor JDK.
func VendorPackageName(distribution string, major int) string {
	return fmt.Sprintf("ctyl-jdk-%s-%d", distribution, major)
}

var safeRE = regexp.MustCompile(`^[A-Za-z0-9._+-]+$`)

// RenderVendorMelange returns a melange recipe that repackages verified vendor
// archives. The archives' sha256 are re-checked inside the build sandbox.
func RenderVendorMelange(in VendorInput) ([]byte, error) {
	for _, s := range []string{in.Distribution, in.Version} {
		if !safeRE.MatchString(s) {
			return nil, fmt.Errorf("unsafe value %q", s)
		}
	}
	var cases strings.Builder
	for _, a := range in.Archives {
		file := filepath.Base(a.File)
		if !safeRE.MatchString(file) || !safeRE.MatchString(a.TopDir) || !shaRE.MatchString(a.SHA256) || !safeRE.MatchString(a.Arch) {
			return nil, fmt.Errorf("unsafe archive metadata %+v", a)
		}
		fmt.Fprintf(&cases, "          %s) f=%s; sum=%s ;;\n", a.Arch, file, a.SHA256)
	}
	home := fmt.Sprintf("java-%d-%s", in.Line.Major, in.Distribution)
	recipe := fmt.Sprintf(`# Generated by ctyl vendor-fetch. Do not edit.
package:
  name: %[1]s
  version: "%[2]s"
  epoch: 0
  description: %[3]s %[4]d (verified vendor archive) repackaged for ctyl
  copyright:
    - license: %[5]s
  dependencies:
    runtime:
      - java-cacerts

environment:
  contents:
    repositories:
      - https://packages.wolfi.dev/os
    keyring:
      - https://packages.wolfi.dev/os/wolfi-signing.rsa.pub
    packages:
      - busybox

pipeline:
  - name: install verified archive
    runs: |
      set -eu
      case "${{build.arch}}" in
%[6]s          *) echo "no verified archive for ${{build.arch}}"; exit 1 ;;
      esac
      echo "$sum  $f" | sha256sum -c -
      dest="${{targets.destdir}}/usr/lib/jvm/%[7]s"
      mkdir -p "$dest" "${{targets.destdir}}/usr/bin"
      tar -xzf "$f" -C "$dest" --strip-components=1 --no-same-owner
      for b in "$dest"/bin/*; do
        case "$(basename "$b")" in java|keytool|jfr) ;; *) rm -f "$b" ;; esac
      done
      rm -rf "$dest/include" "$dest/jmods" "$dest/man" "$dest/demo" "$dest/sample" "$dest/lib/src.zip"
      rm -f "$dest/lib/security/cacerts"
      ln -s /etc/ssl/certs/java/cacerts "$dest/lib/security/cacerts"
      ln -s %[7]s "${{targets.destdir}}/usr/lib/jvm/default-jvm"
      for b in java keytool jfr; do
        if [ -e "$dest/bin/$b" ]; then ln -s "../lib/jvm/default-jvm/bin/$b" "${{targets.destdir}}/usr/bin/$b"; fi
      done

test:
  environment:
    contents:
      repositories:
        - https://packages.wolfi.dev/os
      keyring:
        - https://packages.wolfi.dev/os/wolfi-signing.rsa.pub
      packages:
        - busybox
  pipeline:
    - name: every shared object resolves against Wolfi
      runs: |
        fail=0
        for f in $(find /usr/lib/jvm/%[7]s -name '*.so'); do
          if ld.so --list "$f" 2>&1 | grep -q 'not found'; then
            echo "unresolved dependencies in $f:"; ld.so --list "$f" | grep 'not found'; fail=1
          fi
        done
        exit $fail
    - name: runtime starts with the expected home
      runs: |
        java -version
        java -XshowSettings:properties -version 2>&1 | grep -q 'java.home = /usr/lib/jvm/%[7]s'
`, VendorPackageName(in.Distribution, in.Line.Major), in.Version, strings.ToUpper(in.Distribution[:1])+in.Distribution[1:], in.Line.Major, in.License, cases.String(), home)
	return []byte(recipe), nil
}

var shaRE = regexp.MustCompile(`^[0-9a-f]{64}$`)
